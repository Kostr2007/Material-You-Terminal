#!/usr/bin/env python3
"""Render motion QA artifacts without a running terminal or user configuration."""
import argparse
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "cli"))
from myt_logo import export_studio

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--out", type=Path, default=Path("logo-preview"))
parser.add_argument("--palette", type=Path, help="palette.json generated by myt")
parser.add_argument("--light", action="store_true")
args = parser.parse_args()
palette = {"primary": "#97ccf8", "tertiary": "#e7b9d6", "on_surface": "#e7e1eb", "surface": "#17151d"}
if args.light:
    palette.update(primary="#345e86", tertiary="#80516f", on_surface="#211e26", surface="#faf7ff")
if args.palette:
    palette = json.loads(args.palette.read_text())["colors"]
metrics = export_studio(palette, {"durationMs": 1400, "fps": 30, "idlePeriodMs": 4800}, args.out)
print(json.dumps(metrics, indent=2))
if not all(metrics[k] for k in ("endpointEqual", "handoffEqual", "seamWithinMotion")):
    raise SystemExit("Motion discontinuity: inspect the contact sheet and endpoint frames")
print(args.out.resolve() / "index.html")
